package com.freelance.tests.audit;

import com.freelance.auth.dto.AuthLoginRequestDTO;
import com.freelance.tests.BaseIntegrationTest;
import io.restassured.RestAssured;
import io.restassured.http.ContentType;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.UUID;

import static org.hamcrest.Matchers.*;

@DisplayName("X-Trace-ID Header & Telemetry Integration Tests")
class TraceIdIntegrationTest extends BaseIntegrationTest {

    @Test
    @DisplayName("server generates X-Trace-ID when none is provided in request")
    void traceId_autoGenerated_whenNotProvided() {
        RestAssured
                .given()
                .contentType(ContentType.JSON)
                .body(new AuthLoginRequestDTO("superadmin", "Welcome@1"))
                .when()
                .post("/auth/login")
                .then()
                .statusCode(200)
                .header("X-Trace-ID", notNullValue())
                .header("X-Trace-ID", not(emptyString()));
    }

    @Test
    @DisplayName("server echoes client provided X-Trace-ID in response header")
    void traceId_echoed_whenProvidedInRequest() {
        String customTraceId = "custom-trace-" + UUID.randomUUID();

        RestAssured
                .given()
                .header("X-Trace-ID", customTraceId)
                .contentType(ContentType.JSON)
                .body(new AuthLoginRequestDTO("superadmin", "Welcome@1"))
                .when()
                .post("/auth/login")
                .then()
                .statusCode(200)
                .header("X-Trace-ID", equalTo(customTraceId));
    }

    @Test
    @DisplayName("server returns X-Trace-ID even on error responses")
    void traceId_returned_onErrors() {
        String customTraceId = "error-trace-" + UUID.randomUUID();

        RestAssured
                .given()
                .header("X-Trace-ID", customTraceId)
                .contentType(ContentType.JSON)
                .body(new AuthLoginRequestDTO("superadmin", "WrongPass"))
                .when()
                .post("/auth/login")
                .then()
                .statusCode(400)
                .header("X-Trace-ID", equalTo(customTraceId));
    }
}
